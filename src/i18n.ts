const DICT: Record<Lang, Record<I18nKey, string>> = { en, ar };

let current: Lang = "en";

export const setLang = (l: Lang): void => { current = l; };
export const getLang = (): Lang => current;
export const dir = (): "rtl" | "ltr" => (current === "ar" ? "rtl" : "ltr");

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s = DICT[current][key] ?? en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  return s;
}

/** Pick the localized variant of a user-entered field. */
export const loc = (base: string, arabic?: string): string => (current === "ar" && arabic && arabic.trim() ? arabic : base);

export const dowName = (d: number): string => t(("dow" + d) as I18nKey);

export function niceDate(key: string): string {
  const d = new Date(key + "T00:00:00");
  return d.toLocaleDateString(current === "ar" ? "ar-EG" : "en-US", { weekday: "short", day: "numeric", month: "short" });
}

export function monthLabel(month: string): string {
  const d = new Date(month + "-01T00:00:00");
  return d.toLocaleDateString(current === "ar" ? "ar-EG" : "en-US", { month: "long", year: "numeric" });
}
